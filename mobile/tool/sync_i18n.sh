#!/bin/zsh
# Regenerates lib/i18n/en.g.dart from the web's English dictionary (src/lib/i18n/en), so app and website
# translate the same German texts the same way. Needs a running dev server (pnpm dev or pnpm dev:lan).
# App-only texts go into src/lib/i18n/en/mobile.ts first.
set -e
BASE=${1:-http://localhost:3007}
OUT=${0:A:h:h}/lib/i18n/en.g.dart
mkdir -p ${OUT:h}
curl -sf "$BASE/api/app/i18n" | python3 -c '
import sys, json
words = json.load(sys.stdin)["data"]
def lit(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")
lines = ["// GENERATED by tool/sync_i18n.sh from src/lib/i18n/en – do not edit by hand.", "", "const enDictionary = <String, String>{"]
for de in sorted(words):
    lines.append(f"  {lit(de)}: {lit(words[de])},")
lines.append("};")
print("\n".join(lines))
' > "$OUT"
echo "$(grep -c '^  "' "$OUT") Einträge nach $OUT geschrieben"
