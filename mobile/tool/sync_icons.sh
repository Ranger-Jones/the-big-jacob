#!/bin/zsh
# Regenerates lib/widgets/jakob_icons.g.dart from the web's "Hofstaat" icon set (src/components/ui/icons.tsx),
# so app and website share the very same icons. Needs a running dev server (pnpm dev or pnpm dev:lan).
set -e
BASE=${1:-http://localhost:3007}
OUT=${0:A:h:h}/lib/widgets/jakob_icons.g.dart
curl -sf "$BASE/api/app/icons" | python3 -c '
import sys, json
icons = json.load(sys.stdin)["data"]
lines = ["// GENERATED by tool/sync_icons.sh from src/components/ui/icons.tsx – do not edit by hand.", "", "const jakobIconSvgs = <String, String>{"]
for name in sorted(icons):
    svg = icons[name].replace("\\\\", "\\\\\\\\").replace("\x27", "\\\\\x27")
    lines.append(f"  \x27{name}\x27: \x27{svg}\x27,")
lines.append("};")
print("\n".join(lines))
' > "$OUT"
echo "$(grep -c "^  '" "$OUT") Icons nach $OUT geschrieben"
